// Builds components/chat-examples/reactions/emojiData.ts from emoji-datasource.
// The full dataset is a 1.3 MB JSON; the reactions panel needs only each
// emoji's character, category and search words, so it ships this instead.
// Run after bumping emoji-datasource: `node scripts/build-emoji-data.js`, then the
// root `yarn lint:fix` (the output uses JSON quoting; lint wants single quotes).
const emojis = require('emoji-datasource')
const fs = require('fs')
const path = require('path')

const CATEGORIES = [
  'Smileys & Emotion',
  'People & Body',
  'Animals & Nature',
  'Food & Drink',
  'Travel & Places',
  'Activities',
  'Objects',
  'Symbols',
  'Flags',
]

const toChar = unified => String.fromCodePoint(...unified.split('-').map(hex => parseInt(hex, 16)))

const byCategory = CATEGORIES.map(category => emojis
  .filter(emoji => emoji.category === category)
  .sort((a, b) => a.sort_order - b.sort_order)
  .map(emoji => [
    toChar(emoji.unified),
    [...new Set([emoji.name, ...emoji.short_names].map(word => word.toLowerCase().replace(/_/g, ' ')))].join(' '),
  ]))

const version = require('emoji-datasource/package.json').version
const body = CATEGORIES.map((category, i) =>
  `  [${JSON.stringify(category)}, [\n${byCategory[i].map(([char, words]) => `    [${JSON.stringify(char)}, ${JSON.stringify(words)}],`).join('\n')}\n  ]],`
).join('\n')

const out = `// Generated by scripts/build-emoji-data.js from emoji-datasource ${version}. Do not edit.
// [category, [[emoji, search words], ...]] in Unicode's order.
export const EMOJI_DATA: ReadonlyArray<readonly [string, ReadonlyArray<readonly [string, string]>]> = [
${body}
]
`
const target = path.join(__dirname, '..', 'components', 'chat-examples', 'reactions', 'emojiData.ts')
fs.writeFileSync(target, out)
console.log(`wrote ${path.relative(process.cwd(), target)} (${(out.length / 1024).toFixed(0)} KB)`)
