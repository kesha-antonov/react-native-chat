// Builds src/emoji/emojiData.ts from emoji-datasource (a root devDependency).
//
// The full dataset is a 1.3 MB JSON. The emoji keyboard needs only each emoji's character, its
// tab, whether it takes a skin tone, and a few search words, so it ships this compact table
// instead: one string of emojis and one string of search words per tab.
//
// Run after bumping emoji-datasource: `node scripts/build-emoji-data.cjs`.
const emojis = require('emoji-datasource')
const fs = require('fs')
const path = require('path')

// Emoji keyboard tabs: smileys and people share one, and activities come before
// travel, unlike Unicode's order.
const TABS = [
  ['smileys', ['Smileys & Emotion', 'People & Body']],
  ['animals', ['Animals & Nature']],
  ['food', ['Food & Drink']],
  ['activities', ['Activities']],
  ['travel', ['Travel & Places']],
  ['objects', ['Objects']],
  ['symbols', ['Symbols']],
  ['flags', ['Flags']],
]

const TONES = ['1F3FB', '1F3FC', '1F3FD', '1F3FE', '1F3FF']
const toChar = unified => String.fromCodePoint(...unified.split('-').map(hex => parseInt(hex, 16)))

// The runtime applies a tone by putting the modifier after the first code point (dropping a
// variation selector there). Only emojis where that gives Unicode's exact sequence for every
// tone are marked, so the keyboard never produces a broken one.
const withTone = (unified, tone) => {
  const parts = unified.split('-')
  const rest = parts.slice(1)
  if (rest[0] === 'FE0F')
    rest.shift()
  return [parts[0], tone, ...rest].join('-')
}
const takesTone = emoji => {
  const variations = emoji.skin_variations
  if (!variations)
    return false
  return TONES.every(tone => variations[tone] && variations[tone].unified === withTone(emoji.unified, tone))
}

// Separators that never occur inside an emoji or a search word.
const EMOJI_SEPARATOR = ' '
const WORD_SEPARATOR = '|'
const TONE_MARK = '~'

let toned = 0
const rows = TABS.map(([key, categories]) => {
  const list = emojis
    .filter(emoji => categories.includes(emoji.category) && !emoji.obsoleted_by)
    .sort((a, b) => a.sort_order - b.sort_order)

  const chars = list.map(emoji => {
    const tone = takesTone(emoji)
    if (tone)
      toned += 1
    return toChar(emoji.unified) + (tone ? TONE_MARK : '')
  })
  const words = list.map(emoji => [...new Set(
    [emoji.name, ...emoji.short_names]
      .map(word => word.toLowerCase().replace(/[_:]/g, ' ').replace(/\s+/g, ' ').trim())
  )].join(' '))

  return [key, chars.join(EMOJI_SEPARATOR), words.join(WORD_SEPARATOR)]
})

const version = require('emoji-datasource/package.json').version
const out = `// Generated by scripts/build-emoji-data.cjs from emoji-datasource ${version}. Do not edit.
// One row per keyboard tab: [tab, emojis separated by '${EMOJI_SEPARATOR}', search words per emoji
// separated by '${WORD_SEPARATOR}']. An emoji that takes a skin tone ends in '${TONE_MARK}'.
export const EMOJI_DATA: ReadonlyArray<readonly [string, string, string]> = [
${rows.map(row => `  [${row.map(value => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`).join(', ')}],`).join('\n')}
]
`

const target = path.join(__dirname, '..', 'src', 'emoji', 'emojiData.ts')
fs.writeFileSync(target, out)
const count = rows.reduce((sum, row) => sum + row[1].split(EMOJI_SEPARATOR).length, 0)
console.log(`wrote ${path.relative(process.cwd(), target)}: ${count} emojis, ${toned} with skin tones, ${(Buffer.byteLength(out) / 1024).toFixed(0)} KB`)
